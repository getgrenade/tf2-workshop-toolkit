class TF2_OT_BakeAssetNormal(Operator):
    """Bake a tangent-space normal map for this asset using its _lod0 and _high collections. Settings are read from the Bake Tools panel."""
    bl_idname  = "tf2.bake_asset_normal"
    bl_label   = "Bake Normal Map"
    bl_options = {"REGISTER", "UNDO"}

    asset_name: StringProperty()

    @classmethod
    def poll(cls, context):
        return bool(context.scene.tf2_assets)

    def execute(self, context):
        from . import bake_tools   # lazy import to avoid circular deps

        props = context.scene.bake_props

        # Gather low meshes from _lod0
        low_coll = bpy.data.collections.get(self.asset_name + "_lod0")
        if not low_coll:
            self.report({"ERROR"},
                        f"Collection '{self.asset_name}_lod0' not found.")
            return {"CANCELLED"}

        low_meshes = [o for o in low_coll.objects
                      if o.type == "MESH"]
        if not low_meshes:
            self.report({"ERROR"},
                        f"No meshes in '{self.asset_name}_lod0'.")
            return {"CANCELLED"}

        # Gather high meshes from _high (optional — self-bake if absent)
        high_coll  = bpy.data.collections.get(self.asset_name + "_high")
        high_meshes = []
        if high_coll:
            high_meshes = [o for o in high_coll.objects
                           if o.type == "MESH"]

        # Force-show all relevant collections and objects for the duration of
        # the bake.  Blender refuses to bake hidden objects/collections, but
        # the user may have them hidden in the asset panel.  We save every
        # hide flag we touch and restore them all in a finally block so the
        # viewport state is always left exactly as the user had it.
        colls_to_show = [c for c in [low_coll, high_coll] if c is not None]
        all_objs      = low_meshes + high_meshes

        # (collection, attr, original_value)
        coll_state = [(c, "hide_viewport", c.hide_viewport) for c in colls_to_show] +                      [(c, "hide_render",   c.hide_render)   for c in colls_to_show]
        # (object, attr, original_value)
        obj_state  = [(o, "hide_viewport", o.hide_viewport) for o in all_objs] +                      [(o, "hide_render",   o.hide_render)   for o in all_objs] +                      [(o, "hide_set",      None)            for o in all_objs]

        try:
            # Unhide collections
            for c in colls_to_show:
                c.hide_viewport = False
                c.hide_render   = False

            # Unhide individual objects (hide_set is the "H" key in viewport)
            for o in all_objs:
                o.hide_viewport = False
                o.hide_render   = False
                o.hide_set(False)

            # Use the same name-matching logic as the manual bake panel:
            # _build_bake_sets pairs each _low with its matching _high(s)
            # by stripping the suffix and comparing base names, so
            # "mesh1_low" only bakes against "mesh1_high" / "mesh1_high.001"
            # and never against "mesh2_high".
            all_meshes = low_meshes + high_meshes
            bake_sets, orphans = bake_tools._build_bake_sets(all_meshes)
            if orphans:
                self.report({"WARNING"},
                            f"HIGHs with no matching LOW (skipped): {', '.join(orphans)}")

            # Group the resulting bake sets by material image name so that:
            #   (a) meshes sharing a material accumulate into one image
            #       (single _run_bake_sets call, use_clear only on first)
            #   (b) we can hide all other-material lows during each group's
            #       bake to prevent cross-material ray projection
            from collections import OrderedDict
            # img_name → list of bake_set dicts
            img_groups = OrderedDict()
            for bset in bake_sets:
                low = bset["low"]
                mat = low.data.materials[0] if low.data.materials and low.data.materials[0] else None
                img_name = f"{mat.name}_normal" if mat else "normal_bake"
                img_groups.setdefault(img_name, []).append(bset)

            # Expose first image name for composite/save buttons.
            # output_name is a StringProperty — safe to set now.
            # composite_base_pick is a dynamic EnumProperty that only accepts
            # values present in bpy.data.images at the moment of assignment,
            # so it must be set AFTER the bake loop creates the image.
            first_img = next(iter(img_groups), "normal_bake")
            props.output_name = first_img

            result = {"FINISHED"}
            for img_name, group_sets in img_groups.items():
                group_lows = [bs["low"] for bs in group_sets]

                # Hide every low NOT in this group via hide_set so the
                # Cycles depsgraph (used by selected-to-active bake) truly
                # excludes them — hide_viewport/render alone is not enough.
                other_lows = [l for l in low_meshes if l not in group_lows]
                saved_hide = [(o, o.hide_viewport, o.hide_render) for o in other_lows]
                for o in other_lows:
                    o.hide_viewport = True
                    o.hide_render   = True
                    o.hide_set(True)

                try:
                    result = bake_tools._run_bake_sets(
                        self, context, group_sets, img_name, props
                    )
                finally:
                    for o, hv, hr in saved_hide:
                        o.hide_viewport = hv
                        o.hide_render   = hr
                        o.hide_set(False)

                if result != {"FINISHED"}:
                    break

            # Now the image exists — safe to set the enum picker.
            if bpy.data.images.get(first_img):
                props.composite_base_pick = first_img

            # Wire each unique material to its correctly-named bake image
            if result == {"FINISHED"}:
                for img_name, group_sets in img_groups.items():
                    baked_img = bpy.data.images.get(img_name)
                    if not baked_img:
                        continue
                    seen_mats = set()
                    for bset in group_sets:
                        for slot in bset["low"].material_slots:
                            if slot.material and slot.material not in seen_mats:
                                _wire_normal_image_to_material(slot.material, baked_img)
                                seen_mats.add(slot.material)

        finally:
            # Restore collection visibility
            for c, attr, val in coll_state:
                setattr(c, attr, val)
            # Restore object visibility
            for o, attr, val in obj_state:
                if attr == "hide_set":
                    pass  # hide_set is write-only; viewport/render flags cover it
                else:
                    setattr(o, attr, val)

        return result


class TF2_OT_QuickExport(Operator):
    """Export all flagged assets as game-ready FBX files to the /mesh/ folder."""
    bl_idname = "tf2.quick_export"
    bl_label = "Quick Export Flagged"
    bl_options = {"REGISTER", "UNDO"}

    def execute(self, context):
        if not bpy.data.is_saved:
            self.report({"ERROR"}, "Save your Blender file first!")
            return {"CANCELLED"}

        project_dir = os.path.dirname(bpy.data.filepath)
        export_dir = os.path.join(project_dir, "mesh")
        if not os.path.exists(export_dir):
            os.makedirs(export_dir)

        export_assets = [item for item in context.scene.tf2_assets if item.do_export]
        if not export_assets:
            self.report({"WARNING"}, "No assets flagged for export!")
            return {"CANCELLED"}

        target_lods = ["_lod0", "_lod1", "_lod2"]
        original_active = context.view_layer.objects.active
        exported_files = 0

        for asset in export_assets:
            real_suffixes = get_lod_suffixes(is_library=asset.is_library)

            # Find the asset's armature once (from any mesh in lod0). Used
            # by every LOD's re-centering step below — not just lod0 — so
            # that every LOD's exported geometry sits at world origin
            # regardless of where the variant is parked in the viewport.
            asset_armature = None
            asset_lod0 = bpy.data.collections.get(asset.name + real_suffixes[0])
            if asset_lod0:
                for obj in asset_lod0.objects:
                    if obj.type == "MESH":
                        for mod in obj.modifiers:
                            if mod.type == "ARMATURE" and mod.object:
                                asset_armature = mod.object
                                break
                    if asset_armature:
                        break

            for i, standard_suffix in enumerate(target_lods):
                if i >= len(real_suffixes):
                    break
                actual_suffix = real_suffixes[i]
                coll_name = asset.name + actual_suffix
                coll = bpy.data.collections.get(coll_name)
                if not coll:
                    continue

                export_coll = bpy.data.collections.new(coll_name + "_temp")
                context.scene.collection.children.link(export_coll)

                # Per-LOD reference to the same armature; only the first LOD
                # actually includes the armature in the export selection.
                target_armature = asset_armature if i == 0 else None

                temp_meshes = []
                for obj in coll.objects:
                    if obj.type != "MESH":
                        continue
                    new_obj = obj.copy()
                    new_obj.data = obj.data.copy()
                    export_coll.objects.link(new_obj)
                    processed_obj = apply_modifiers_with_shapekeys(
                        context, new_obj, export_coll
                    )
                    temp_meshes.append(processed_obj)

                if not temp_meshes:
                    bpy.data.collections.remove(export_coll)
                    continue

                bpy.ops.object.select_all(action="DESELECT")
                for m in temp_meshes:
                    m.select_set(True)
                context.view_layer.objects.active = temp_meshes[0]

                bpy.ops.object.parent_clear(type="CLEAR_KEEP_TRANSFORM")
                bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
                bpy.ops.object.join()

                final_mesh = context.view_layer.objects.active
                final_mesh.name = coll_name + "_merged"

                # After join, add the armature modifier back.
                # join() keeps only the active object's modifiers and
                # apply_modifiers_with_shapekeys converts/applies all modifiers
                # (including armature) into the mesh data, so the modifier is
                # gone by this point. Re-add it so the FBX exporter sees the
                # mesh correctly bound to the skeleton.
                if target_armature:
                    # Remove any stale armature mods that survived
                    for mod in list(final_mesh.modifiers):
                        if mod.type == "ARMATURE":
                            final_mesh.modifiers.remove(mod)
                    arm_mod = final_mesh.modifiers.new(name="Armature", type="ARMATURE")
                    arm_mod.object = target_armature

                if i == 0 and target_armature:
                    if target_armature.name not in export_coll.objects:
                        export_coll.objects.link(target_armature)
                    target_armature.select_set(True)

                final_mesh.select_set(True)
                fbx_path = os.path.join(export_dir, f"{coll_name}.fbx")

                # ── Re-center for export ────────────────────────────────
                # Shift both the merged mesh and the asset's armature so
                # they end up at world origin in the FBX. The mesh has the
                # variant's All-Class spread (and any other authoring
                # offset) baked into its vertex coords by the earlier
                # transform_apply, and the armature sits at whatever world
                # position the user has it parked at in the scene. Without
                # this step the FBX records both at +X (matching the
                # scene), so when imported standalone — without being
                # re-attached to a player skeleton in the engine — the
                # entire model floats away from origin.
                #
                # Both objects get shifted by the SAME amount — the
                # armature's world translation — so their relative
                # positions don't change and the rigging stays correct.
                # The shift is applied to the mesh by transform_apply
                # (baked into verts) and to the armature by direct
                # matrix_world write, which we restore after export so
                # the user's scene layout is untouched.
                saved_arm_matrix = None
                if asset_armature:
                    offset = asset_armature.matrix_world.translation.copy()
                    if offset.length_squared > 0.0:
                        # Mesh: shift then bake
                        final_mesh.location = final_mesh.location - offset
                        bpy.ops.object.select_all(action="DESELECT")
                        final_mesh.select_set(True)
                        context.view_layer.objects.active = final_mesh
                        bpy.ops.object.transform_apply(
                            location=True, rotation=False, scale=False
                        )
                        # Armature: stash + zero translation
                        saved_arm_matrix = asset_armature.matrix_world.copy()
                        new_mat = saved_arm_matrix.copy()
                        new_mat.translation = (0.0, 0.0, 0.0)
                        asset_armature.matrix_world = new_mat

                        # Re-establish the export selection — the
                        # transform_apply call above wiped it.
                        bpy.ops.object.select_all(action="DESELECT")
                        final_mesh.select_set(True)
                        if i == 0 and target_armature:
                            target_armature.select_set(True)
                        context.view_layer.objects.active = final_mesh

                bpy.ops.export_scene.fbx(
                    filepath=fbx_path,
                    use_selection=True,
                    object_types={"ARMATURE", "MESH"},
                    global_scale=1.0,
                    apply_scale_options="FBX_SCALE_UNITS",
                    axis_forward="-Z",
                    axis_up="Y",
                    bake_anim=False,
                    use_mesh_modifiers=False,
                )
                exported_files += 1

                # Restore the armature's scene position. The mesh was a
                # throwaway temp in export_coll; it gets removed below
                # along with the rest of the temp collection contents,
                # so its baked-in shift is forgotten naturally.
                if saved_arm_matrix is not None:
                    asset_armature.matrix_world = saved_arm_matrix

                if i == 0 and target_armature:
                    export_coll.objects.unlink(target_armature)

                for o in list(export_coll.objects):
                    if o.type == "MESH":
                        data = o.data
                        bpy.data.objects.remove(o, do_unlink=True)
                        if data.users == 0:
                            bpy.data.meshes.remove(data)
                    else:
                        bpy.data.objects.remove(o, do_unlink=True)

                bpy.data.collections.remove(export_coll)

        if original_active:
            context.view_layer.objects.active = original_active
        self.report({"INFO"}, f"TF2 Export Complete: {exported_files} files exported.")
        return {"FINISHED"}


class TF2_OT_RegisterSelected(Operator):
    """Register the selected object or collection as a tracked asset."""
    bl_idname = "tf2.register_selected"
    bl_label = "Register Asset"
    asset_name: StringProperty(name="Detected Asset")
    is_lib: BoolProperty()
    do_sync: BoolProperty(name="Sync Material Names?", default=True)
    two_mats: BoolProperty(name="Use Two Materials? (A/Z)", default=False)

    def draw(self, context):
        layout = self.layout
        layout.prop(self, "asset_name")
        box = layout.box()
        box.prop(self, "do_sync")
        sub = box.row()
        sub.active = self.do_sync
        sub.prop(self, "two_mats")

    def execute(self, context):
        if not any(item.name == self.asset_name for item in context.scene.tf2_assets):
            new_item = context.scene.tf2_assets.add()
            new_item.name = self.asset_name
            new_item.old_name = self.asset_name
            new_item.is_library = self.is_lib
        if not self.is_lib and self.do_sync:
            perform_material_sync(self.asset_name, self.two_mats)
        collapse_all_collections()
        return {"FINISHED"}

    def invoke(self, context, event):
        potential_names = set()
        if context.collection:
            potential_names.add(context.collection.name)
        for obj in context.selected_objects:
            potential_names.add(obj.name)
            for coll in obj.users_collection:
                potential_names.add(coll.name)

        target_base, target_lib = None, False
        for p_name in potential_names:
            base, is_lib = detect_asset_from_name(p_name)
            if not base:
                root = bpy.data.collections.get(p_name)
                if root:
                    for child in root.children:
                        b, lib = detect_asset_from_name(child.name)
                        if b:
                            base, is_lib = b, lib
                            break
            if not base:
                base = p_name
            test_sfx = "_morphs_low_lod0" if is_lib else "_lod0"
            if bpy.data.collections.get(base + test_sfx):
                target_base, target_lib = base, is_lib
                break

        if not target_base:
            return {"CANCELLED"}
        self.asset_name, self.is_lib = target_base, target_lib
        if not self.is_lib:
            return context.window_manager.invoke_props_dialog(self)
        return self.execute(context)


class TF2_OT_InitializeAsset(Operator):
    """Create a new asset with lod0/lod1/lod2/high collections and a starter material."""
    bl_idname = "tf2.initialize_asset"
    bl_label = "Initialize TF2 Asset"
    asset_name: StringProperty(name="Asset Name", default="cosmetic")
    use_two_mats: BoolProperty(name="Create Two Materials?", default=False)

    def _unique_name(self, base):
        """Strip any trailing _N suffix, then find the next free name."""
        base = re.sub(r"_\d+$", "", base)
        existing = {i.name for i in bpy.context.scene.tf2_assets}
        existing |= {c.name for c in bpy.data.collections}
        if base not in existing:
            return base
        index = 2
        while f"{base}_{index}" in existing:
            index += 1
        return f"{base}_{index}"

    def invoke(self, context, event):
        # Pre-fill with a guaranteed-unique name so the dialog already shows it
        self.asset_name = self._unique_name(self.asset_name)
        return context.window_manager.invoke_props_dialog(self)

    def execute(self, context):
        name = self.asset_name
        a_mat  = bpy.data.materials.new(name=f"A_{name}")
        _setup_asset_material_nodes(a_mat, name)
        mats = [a_mat]
        if self.use_two_mats:
            mats.append(bpy.data.materials.new(name=f"Z_{name}"))
        configs = [
            (f"{name}_lod0", "COLOR_05"),
            (f"{name}_lod1", "COLOR_05"),
            (f"{name}_lod2", "COLOR_05"),
            (f"{name}_high", "COLOR_06"),
        ]
        for c_name, c_color in configs:
            new_col = bpy.data.collections.new(c_name)
            context.scene.collection.children.link(new_col)
            new_col.color_tag = c_color
        new_item = context.scene.tf2_assets.add()
        new_item.name, new_item.old_name = name, name
        collapse_all_collections()
        return {"FINISHED"}


class TF2_OT_DuplicateAsset(Operator):
    bl_idname = "tf2.duplicate_asset"
    bl_label = "Duplicate Asset Variation"
    asset_name: StringProperty()
    create_new_mats: BoolProperty(name="Create New Materials?", default=False)

    def execute(self, context):
        base_item = next(
            i for i in context.scene.tf2_assets if i.name == self.asset_name
        )
        base_name = self.asset_name
        indices = [0]
        for c in bpy.data.collections:
            match = re.search(rf"{re.escape(base_name)}_s(\d+)_lod0", c.name)
            if match:
                indices.append(int(match.group(1)))
        next_idx = max(indices) + 1
        new_base = f"{base_name}_s{next_idx}"
        mat_map = {}
        if self.create_new_mats:
            for p in ["A_", "Z_"]:
                old = bpy.data.materials.get(f"{p}{base_name}")
                if old:
                    new = old.copy()
                    new.name = f"{p}{new_base}"
                    mat_map[old] = new
        suffixes = get_lod_suffixes(is_library=base_item.is_library)
        if "_high" in suffixes:
            suffixes.remove("_high")
        for sfx in suffixes:
            source = bpy.data.collections.get(base_name + sfx)
            if not source:
                continue
            new_col = bpy.data.collections.new(new_base + sfx)
            context.scene.collection.children.link(new_col)
            new_col.color_tag = source.color_tag
            for o in source.objects:

                new_o = o.copy()
                if o.type != "ARMATURE" and o.data:
                    new_o.data = o.data.copy()
                new_col.objects.link(new_o)
                if self.create_new_mats:
                    for slot in new_o.material_slots:
                        if slot.material in mat_map:
                            slot.material = mat_map[slot.material]
        new_item = context.scene.tf2_assets.add()
        new_item.name = new_base
        new_item.old_name = new_base
        new_item.is_library = base_item.is_library
        collapse_all_collections()
        return {"FINISHED"}

    def invoke(self, context, event):
        return context.window_manager.invoke_props_dialog(self)


