class TF2_OT_LODStatsTip(Operator):
    """Show detailed triangle stats for a single LOD"""
    bl_idname  = "tf2.lod_stats_tip"
    bl_label   = ""
    bl_options = {"INTERNAL"}

    asset_name: StringProperty()
    lod_suffix: StringProperty()   # e.g. "_lod0"

    @classmethod
    def description(cls, context, props):
        limit = LOD_LIMITS.get(props.lod_suffix)
        coll  = bpy.data.collections.get(props.asset_name + props.lod_suffix)
        if coll is None:
            return f"LOD{props.lod_suffix[-1]} — collection not found"
        count = _tri_count(coll)
        if limit is None:
            return f"LOD{props.lod_suffix[-1]} — {count:,} tris"
        pct    = 100.0 * count / limit
        over   = count > limit
        status = f"OVER LIMIT by {count - limit:,}" if over else f"{limit - count:,} remaining"
        return f"LOD{props.lod_suffix[-1]}  —  {count:,} / {limit:,} tris  ({pct:.0f}%)  |  {status}"

    def execute(self, context):
        return {"FINISHED"}


class TF2_PT_MainPanel(Panel):
    bl_label = "Workshop Asset Manager"
    bl_idname = "TF2_PT_MainPanel"
    bl_space_type = "VIEW_3D"
    bl_region_type = "UI"
    bl_category = "WS Toolkit"

    def draw(self, context):
        layout = self.layout
        scene = context.scene

        row = layout.row(align=True)
        row.operator("tf2.initialize_asset", text="Initialize", icon="PLAY")
        row.operator("tf2.allclass_generate", text="All-Class", icon="COMMUNITY")
        row.operator("tf2.quick_export", text="Export Flagged", icon="EXPORT")
        row.operator("tf2.register_selected", text="", icon="FILE_REFRESH")
        layout.separator()

        for index, item in enumerate(scene.tf2_assets):
            row = layout.row(align=True)

            if not item.is_library:
                row.prop(
                    item, "show_stats", text="", emboss=False,
                    icon="TRIA_DOWN" if item.show_stats else "TRIA_RIGHT",
                )
            else:
                row.label(text="", icon="BLANK1")

            row.prop(item, "do_export", text="", icon="EXPORT", toggle=True)
            row.operator("tf2.duplicate_asset", text="", icon="ADD").asset_name = item.name

            has_lod0 = bpy.data.collections.get(item.name + "_lod0") is not None
            has_high = bpy.data.collections.get(item.name + "_high") is not None
            if has_lod0 and hasattr(scene, "bake_props"):
                op = row.operator("tf2.bake_asset_normal", text="", icon="IMAGE_DATA")
                op.asset_name = item.name
                if not has_high:
                    row.label(text="", icon="INFO")

            split = row.split(factor=0.55, align=True)
            split.prop(item, "name", text="")
            btn_row = split.row(align=True)
            for i in range(3):
                btn_row.prop(item, f"show_lod{i}", toggle=True, text=str(i))
            if not item.is_library and has_high:
                btn_row.prop(item, "show_high", toggle=True, text="H")
            else:
                btn_row.label(text="", icon="BLANK1")
            btn_row.separator(factor=1.5)
            del_op = btn_row.operator("tf2.remove_asset", text="", icon="TRASH")
            del_op.index, del_op.asset_name = index, item.name

            # ── Expandable stats row ──────────────────────────────────── #
            if not item.is_library and item.show_stats:
                stats_row = layout.row(align=True)
                stats_row.scale_y = 0.7
                stats_row.alignment = "RIGHT"
                for suffix, limit_val in LOD_LIMITS.items():
                    coll = bpy.data.collections.get(item.name + suffix)
                    if coll is None:
                        continue
                    count = _tri_count(coll)
                    over  = count > limit_val
                    op = stats_row.operator(
                        "tf2.lod_stats_tip",
                        text=f"{count:,}/{limit_val:,}",
                        icon="ERROR" if over else "CHECKMARK",
                        emboss=False,
                    )
                    op.asset_name = item.name
                    op.lod_suffix = suffix


