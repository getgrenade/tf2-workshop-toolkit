TF2_CLASSES = (
    "scout", "soldier", "pyro", "demo", "heavy",
    "engineer", "medic", "sniper", "spy",
)


def _detect_class_from_armature(arm_obj):
    """Return the class name parsed from an armature named '<class>_ARM',
    or None if the armature name doesn't match the pattern or the prefix
    isn't a known TF2 class."""
    if not arm_obj or arm_obj.type != "ARMATURE":
        return None
    name = arm_obj.name
    if not name.endswith("_ARM"):
        return None
    prefix = name[:-len("_ARM")].lower()
    if prefix in TF2_CLASSES:
        return prefix
    return None


def _find_armature_in_collection(coll):
    """Return the first armature referenced by an Armature modifier on any
    mesh in *coll*, or None."""
    if not coll:
        return None
    for obj in coll.objects:
        if obj.type != "MESH":
            continue
        for mod in obj.modifiers:
            if mod.type == "ARMATURE" and mod.object:
                return mod.object
    return None


def _get_target_assets_enum(self, context):
    items = []
    for item in context.scene.tf2_assets:
        if not item.is_library:
            items.append((item.name, item.name, ""))
    if not items:
        items.append(("NONE", "No registered assets", ""))
    return items


LATTICE_NAME_SUFFIX = "_lattice"


def _find_existing_lattice(asset_name):
    """
    Return the lattice object dedicated to *asset_name*, or None.

    We name lattices `<asset_name>_lattice` and create exactly one per
    class variant. The lookup is by object-name only — we don't scan the
    asset's collections, since teardown re-homes lattices to the scene
    root collection when LOD collections are wiped.
    """
    obj = bpy.data.objects.get(asset_name + LATTICE_NAME_SUFFIX)
    if obj and obj.type == "LATTICE":
        return obj
    return None


def _bind_lattice_modifier(mesh_obj, lattice_obj):
    """
    Attach a Lattice modifier on *mesh_obj* pointing at *lattice_obj*.
    Strips any prior Lattice modifiers first so re-binding doesn't pile
    them up across refreshes. Named "Lattice" so it shows up predictably
    in the modifier stack.
    """
    for mod in list(mesh_obj.modifiers):
        if mod.type == "LATTICE":
            mesh_obj.modifiers.remove(mod)
    mod = mesh_obj.modifiers.new(name="Lattice", type="LATTICE")
    mod.object = lattice_obj
    return mod


def _bip_head_local_pos(arm_obj):
    """
    Return the rest-pose position of the 'bip_head' bone in armature-local
    space (i.e. relative to the armature's own origin), or None if the
    armature has no such bone.

    We deliberately use the LOCAL position rather than world space: the
    All-Class flow needs to compare bip_head positions across different
    class armatures purely as a "how tall is this character" measurement.
    Using world space would also pick up wherever the user has parked each
    armature in the viewport — and since people often spread their class
    armatures out on X for visual inspection, that armature placement
    would leak into the head-alignment delta and shift hats sideways
    instead of just up/down. Local space is invariant to armature
    placement: scout_bip_head.head_local stays the same whether scout_ARM
    sits at world (0,0,0) or (500,0,0).
    """
    if not arm_obj or arm_obj.type != "ARMATURE":
        return None
    bone = arm_obj.data.bones.get("bip_head")
    if bone is None:
        return None
    return bone.head_local.copy()


def _strip_class_prefix(asset_name):
    """If *asset_name* starts with one of the TF2 class prefixes, return
    (prefix, base). Otherwise return (None, asset_name)."""
    lower = asset_name.lower()
    for cls in TF2_CLASSES:
        if lower.startswith(cls + "_"):
            return cls, asset_name[len(cls) + 1:]
    return None, asset_name


def _teardown_class_variant(asset_name, lod_suffixes):
    """
    Remove the LOD collections (and their contained mesh objects + orphaned
    mesh data) for a class-variant asset. Used by All-Class refresh so we
    can rebuild from the current source without leaking duplicate meshes.
    Only collections matching `<asset_name><sfx>` exactly are touched.

    Lattice objects (type == "LATTICE") are deliberately skipped: the user
    may have spent significant effort sculpting them, and the All-Class
    operator's lattice toggle treats existing lattices as "carry over and
    re-bind". They are unlinked from the doomed collection and re-homed
    into the scene root collection so they survive the rebuild and can be
    re-linked into the fresh _lod0 collection by the rebuild step.
    """
    scene_coll = bpy.context.scene.collection
    for sfx in lod_suffixes:
        coll = bpy.data.collections.get(asset_name + sfx)
        if not coll:
            continue
        for obj in list(coll.objects):
            if obj.type == "LATTICE":
                # Spare the lattice — re-home it to scene root so it
                # outlives the collection removal below.
                coll.objects.unlink(obj)
                if scene_coll.objects.find(obj.name) == -1:
                    scene_coll.objects.link(obj)
                continue
            data = obj.data if obj.type == "MESH" else None
            bpy.data.objects.remove(obj, do_unlink=True)
            if data is not None and data.users == 0:
                bpy.data.meshes.remove(data)
        bpy.data.collections.remove(coll)


class TF2_OT_AllClassGenerate(Operator):
    """Generate or refresh per-class LOD variants of the selected asset, head-aligned to each TF2 class armature."""
    bl_idname  = "tf2.allclass_generate"
    bl_label   = "Generate All-Class Variants"
    bl_options = {"REGISTER", "UNDO"}

    asset_name: EnumProperty(
        name="Source Asset",
        items=_get_target_assets_enum,
    )

    create_lattices: BoolProperty(
        name="Create Lattices",
        default=True,
        description=(
            "Spawn a 3x3x3 B-spline lattice fitted around each variant's "
            "LOD meshes (lod0/lod1/lod2 share one lattice per class). "
            "Existing lattices are always preserved on refresh — toggle "
            "this off if you've already shaped the lattices and just want "
            "to rebuild geometry without disturbing them"
        ),
    )

    @classmethod
    def poll(cls, context):
        return any(not i.is_library for i in context.scene.tf2_assets)

    def invoke(self, context, event):
        non_lib = [i.name for i in context.scene.tf2_assets if not i.is_library]
        if not non_lib:
            self.report({"ERROR"}, "No registered non-library assets found.")
            return {"CANCELLED"}
        return context.window_manager.invoke_props_dialog(self)

    def execute(self, context):
        scene = context.scene

        if not self.asset_name or self.asset_name == "NONE":
            self.report({"ERROR"}, "No asset selected.")
            return {"CANCELLED"}

        src_item = next(
            (i for i in scene.tf2_assets if i.name == self.asset_name),
            None,
        )
        if src_item is None:
            self.report({"ERROR"}, f"Asset '{self.asset_name}' not found.")
            return {"CANCELLED"}
        if src_item.is_library:
            self.report({"ERROR"}, "Library assets are not supported.")
            return {"CANCELLED"}

        # Resolve the source asset's class via its armature
        src_lod0 = bpy.data.collections.get(self.asset_name + "_lod0")
        if src_lod0 is None:
            self.report({"ERROR"},
                        f"Source collection '{self.asset_name}_lod0' not found.")
            return {"CANCELLED"}

        src_arm = _find_armature_in_collection(src_lod0)
        if src_arm is None:
            self.report({"ERROR"},
                        "Source asset has no Armature modifier — can't detect class.")
            return {"CANCELLED"}

        src_class = _detect_class_from_armature(src_arm)
        if src_class is None:
            self.report({"ERROR"},
                        f"Armature '{src_arm.name}' isn't named '<class>_ARM' "
                        f"with a known TF2 class.")
            return {"CANCELLED"}

        # Determine the shared base name (without any class prefix)
        existing_prefix, base_name = _strip_class_prefix(self.asset_name)

        # Rename source collections + asset entry to carry the class prefix.
        # Material names are deliberately left alone — every variant shares
        # the A_/Z_ materials of the original asset.
        if existing_prefix is None:
            new_src_name = f"{src_class}_{base_name}"
            old_src_name = self.asset_name

            # Skip rename if the target name is already taken (collection
            # collision shouldn't ever happen, but guard anyway)
            if (bpy.data.collections.get(new_src_name + "_lod0")
                    and new_src_name != old_src_name):
                self.report({"WARNING"},
                            f"Collection '{new_src_name}_lod0' already exists — "
                            f"leaving source name as '{old_src_name}'.")
            else:
                # Rename collections directly, bypassing update_asset_name's
                # material-rename behaviour by setting old_name first.
                for sfx in get_lod_suffixes(is_library=False):
                    coll = bpy.data.collections.get(old_src_name + sfx)
                    if coll:
                        coll.name = new_src_name + sfx
                src_item.old_name = new_src_name   # suppress material rename
                src_item.name     = new_src_name
                self.asset_name   = new_src_name

        else:
            # Already has a class prefix; require it match the detected class
            if existing_prefix != src_class:
                self.report({"WARNING"},
                            f"Asset name prefix '{existing_prefix}_' doesn't "
                            f"match detected class '{src_class}'. Continuing "
                            f"with detected class.")

        # ── Build per-class variants ───────────────────────────────── #
        other_classes = [c for c in TF2_CLASSES if c != src_class]

        created  = 0
        refreshed = 0
        no_armat = []
        no_head  = []     # classes whose armature lacks a 'bip_head' bone

        # X-offset stride between class variants in the viewport
        OFFSET_X = 50.0

        # Resolve the source class's bip_head position once. This is the
        # reference point the geometry was authored against, so each
        # variant's head-alignment offset is (target_bip_head - this).
        # If the source armature has no bip_head we fall back to no
        # head-alignment at all (variants get only the X-spread offset).
        src_head_pos = _bip_head_local_pos(src_arm)
        if src_head_pos is None:
            self.report({"WARNING"},
                        f"Source armature '{src_arm.name}' has no 'bip_head' bone — "
                        f"variants will not be height-corrected.")

        # Stash original active/selection so we can restore at the end
        prev_active = context.view_layer.objects.active
        prev_sel    = list(context.selected_objects)

        target_lods = ["_lod0", "_lod1", "_lod2"]

        try:
            for slot_idx, cls_name in enumerate(other_classes):
                target_arm_name = f"{cls_name}_ARM"
                target_arm = bpy.data.objects.get(target_arm_name)
                if target_arm is None or target_arm.type != "ARMATURE":
                    no_armat.append(cls_name)
                    continue

                new_asset_name = f"{cls_name}_{base_name}"

                # Per-class head-alignment delta. Only meaningful when both
                # the source and target armatures have a 'bip_head' bone.
                # If either is missing we leave the variant at the source's
                # geometric position and warn the user.
                head_delta = None
                if src_head_pos is not None:
                    tgt_head_pos = _bip_head_local_pos(target_arm)
                    if tgt_head_pos is None:
                        no_head.append(cls_name)
                    else:
                        head_delta = tgt_head_pos - src_head_pos

                # Detect whether this class variant already exists. If any
                # of its LOD collections is present we treat it as a refresh:
                # tear the old collections down (keeping the asset entry)
                # and rebuild from the current source.
                already_exists = any(
                    bpy.data.collections.get(new_asset_name + sfx) is not None
                    for sfx in target_lods
                )
                if already_exists:
                    _teardown_class_variant(new_asset_name, target_lods)
                    refreshed += 1
                else:
                    created += 1

                # Build empty target collections (LOD0/1/2 only; no _high)
                new_colls = {}
                for sfx in target_lods:
                    nc = bpy.data.collections.new(new_asset_name + sfx)
                    scene.collection.children.link(nc)
                    src_coll = bpy.data.collections.get(self.asset_name + sfx)
                    if src_coll:
                        nc.color_tag = src_coll.color_tag
                    new_colls[sfx] = nc

                # Per-class viewport X offset. Pure object-space stride;
                # we deliberately do NOT compensate for where the user has
                # placed the per-class armatures. The visible spread will
                # appear correct when armatures share a position (or sit
                # at world origin); if armatures are themselves spread out
                # AND in pose mode, the rigged-mesh inheritance will add
                # to this — toggle Pose to Rest with the F4 hotkey or
                # park armatures at origin if a clean stride matters more
                # than your inspection layout.
                # +1 on slot_idx so the source variant sits at x_offset 0
                # and the others march outward.
                x_offset = OFFSET_X * (slot_idx + 1)

                # Merge each LOD: copy → apply mods+shape keys → join
                for sfx in target_lods:
                    src_coll = bpy.data.collections.get(self.asset_name + sfx)
                    if not src_coll:
                        continue

                    target_coll = new_colls[sfx]
                    is_lod0     = (sfx == "_lod0")

                    # 1. Duplicate every mesh into the target collection
                    temp_meshes = []
                    for obj in src_coll.objects:
                        if obj.type != "MESH":
                            continue
                        new_o = obj.copy()
                        new_o.data = obj.data.copy()
                        target_coll.objects.link(new_o)
                        # Apply modifiers / shape keys (this re-creates the
                        # object inside target_coll for shape-keyed meshes)
                        processed = apply_modifiers_with_shapekeys(
                            context, new_o, target_coll
                        )
                        temp_meshes.append(processed)

                    if not temp_meshes:
                        continue

                    # 2. Join all temps into one
                    bpy.ops.object.select_all(action="DESELECT")
                    for m in temp_meshes:
                        m.select_set(True)
                    context.view_layer.objects.active = temp_meshes[0]
                    bpy.ops.object.parent_clear(type="CLEAR_KEEP_TRANSFORM")
                    # Apply transforms BEFORE join so any pre-existing object
                    # offsets on source meshes get baked into geometry — this
                    # matches Quick Export. The per-class X-offset we add
                    # AFTER the join is a fresh, unapplied object translation.
                    bpy.ops.object.transform_apply(
                        location=True, rotation=True, scale=True
                    )
                    if len(temp_meshes) > 1:
                        bpy.ops.object.join()

                    final = context.view_layer.objects.active
                    final.name = new_asset_name + sfx + "_merged"

                    # 3. Re-bind armature for lod0 only.
                    # apply_modifiers_with_shapekeys bakes ALL modifiers into
                    # the mesh data (including armature deformation), so any
                    # surviving armature mod from the copy needs to be wiped
                    # before we attach the per-class one.
                    for mod in list(final.modifiers):
                        if mod.type == "ARMATURE":
                            final.modifiers.remove(mod)
                    if is_lod0:
                        arm_mod = final.modifiers.new(name="Armature",
                                                      type="ARMATURE")
                        arm_mod.object = target_arm

                    # 4. Apply head-alignment delta to GEOMETRY (transform-
                    # applied), so the mesh sits at the target class's head
                    # height. The previous transform_apply call left the
                    # object at identity, so we can drop the delta straight
                    # into .location and bake it into the mesh data.
                    if head_delta is not None:
                        final.location = head_delta
                        bpy.ops.object.select_all(action="DESELECT")
                        final.select_set(True)
                        context.view_layer.objects.active = final
                        bpy.ops.object.transform_apply(
                            location=True, rotation=False, scale=False
                        )

                    # 5. Apply per-class viewport X offset (object location
                    # only — NOT applied — so the variants are visually
                    # spread out without affecting the actual mesh data
                    # that gets exported).
                    final.location.x += x_offset

                # ── Lattice step ─────────────────────────────────────── #
                # One shared lattice per class variant, fitted to the
                # combined bbox of all LOD meshes. Three behaviours:
                #
                #   1. Existing lattice (regardless of toggle):
                #      Re-link it into _lod0 if needed, re-bind a fresh
                #      Lattice modifier on each LOD mesh. Lattice points
                #      are preserved (we never recreate the data).
                #
                #   2. No lattice + toggle ON:
                #      Spawn a new 3x3x3 B-spline lattice via the built-in
                #      operator with selection set to all LOD meshes — it
                #      auto-fits and auto-adds modifiers in one call.
                #
                #   3. No lattice + toggle OFF:
                #      Skip — no lattice for this asset.
                lod_meshes = []
                for sfx in target_lods:
                    coll = bpy.data.collections.get(new_asset_name + sfx)
                    if not coll:
                        continue
                    for o in coll.objects:
                        if o.type == "MESH":
                            lod_meshes.append(o)

                if lod_meshes:
                    existing_lattice = _find_existing_lattice(new_asset_name)
                    lod0_coll = new_colls.get("_lod0")

                    if existing_lattice is not None:
                        # Reuse path: home it back into _lod0 if it ended
                        # up loose in the scene root (teardown re-homes
                        # lattices there to keep them alive), then re-bind
                        # the modifier on every LOD mesh.
                        if (lod0_coll is not None
                                and lod0_coll.objects.find(existing_lattice.name) == -1):
                            for parent_coll in list(existing_lattice.users_collection):
                                parent_coll.objects.unlink(existing_lattice)
                            lod0_coll.objects.link(existing_lattice)
                        for m in lod_meshes:
                            _bind_lattice_modifier(m, existing_lattice)

                    elif self.create_lattices:
                        # Fresh-spawn path: select the LOD meshes and let
                        # the built-in lattice_add_to_selected fit the
                        # lattice and add modifiers in one shot. The 3x3x3
                        # resolution is set at create time; the B-spline
                        # interpolation is set on the lattice data after.
                        bpy.ops.object.select_all(action="DESELECT")
                        for m in lod_meshes:
                            m.select_set(True)
                        context.view_layer.objects.active = lod_meshes[0]
                        bpy.ops.object.lattice_add_to_selected(
                            fit_to_selected=True,
                            add_modifiers=True,
                            resolution_u=3,
                            resolution_v=3,
                            resolution_w=3,
                        )

                        # The freshly created lattice is now active.
                        new_lattice = context.view_layer.objects.active
                        if new_lattice and new_lattice.type == "LATTICE":
                            new_lattice.name = new_asset_name + LATTICE_NAME_SUFFIX
                            # Switch all three axes to B-spline
                            new_lattice.data.interpolation_type_u = "KEY_BSPLINE"
                            new_lattice.data.interpolation_type_v = "KEY_BSPLINE"
                            new_lattice.data.interpolation_type_w = "KEY_BSPLINE"
                            # The operator drops the lattice into the
                            # active collection (usually scene root). Move
                            # it into _lod0 alongside the meshes for tidy
                            # outliner organisation.
                            if lod0_coll is not None:
                                for parent_coll in list(new_lattice.users_collection):
                                    parent_coll.objects.unlink(new_lattice)
                                lod0_coll.objects.link(new_lattice)

                # Register the new asset entry only if one isn't already
                # tracking this name (refresh keeps the existing entry).
                if not any(it.name == new_asset_name for it in scene.tf2_assets):
                    new_item = scene.tf2_assets.add()
                    new_item.name     = new_asset_name
                    new_item.old_name = new_asset_name
                    new_item.is_library = False

        finally:
            bpy.ops.object.select_all(action="DESELECT")
            for o in prev_sel:
                try:
                    o.select_set(True)
                except Exception:
                    pass
            if prev_active:
                try:
                    context.view_layer.objects.active = prev_active
                except Exception:
                    pass
            collapse_all_collections()

        # Build a single info report
        msgs = []
        if created:
            msgs.append(f"created {created}")
        if refreshed:
            msgs.append(f"refreshed {refreshed}")
        if not msgs:
            msgs.append("nothing to do")
        report_line = f"All-Class: {', '.join(msgs)}"
        if no_armat:
            report_line += f" | no '<class>_ARM' for: {', '.join(no_armat)}"
        if no_head:
            report_line += f" | no 'bip_head' on: {', '.join(no_head)}"
        self.report({"INFO"}, report_line)
        return {"FINISHED"}


