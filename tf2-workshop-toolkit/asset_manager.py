def update_asset_name(self, context):
    old, new = self.old_name, self.name
    if old == "" or old == new:
        return
    for prefix in ["A_", "Z_"]:
        mat = bpy.data.materials.get(f"{prefix}{old}")
        if mat:
            mat.name = f"{prefix}{new}"
    root = bpy.data.collections.get(old)
    if root:
        root.name = new
    suffixes = get_lod_suffixes(is_library=self.is_library)
    for sfx in suffixes:
        coll = bpy.data.collections.get(old + sfx)
        if coll:
            coll.name = new + sfx

    self.old_name = new


class TF2AssetItem(PropertyGroup):
    name: StringProperty(name="Asset Name", update=update_asset_name)
    old_name: StringProperty()
    is_library: BoolProperty(default=False)
    do_export: BoolProperty(
        name="Flag for Export",
        default=False,
        description="Flag this asset to be exported",
    )
    show_lod0: BoolProperty(
        default=True,
        update=lambda s, c: sync_visibility(s, "_lod0", s.show_lod0),
    )
    show_lod1: BoolProperty(
        default=True,
        update=lambda s, c: sync_visibility(s, "_lod1", s.show_lod1),
    )
    show_lod2: BoolProperty(
        default=True,
        update=lambda s, c: sync_visibility(s, "_lod2", s.show_lod2),
    )
    show_high: BoolProperty(
        default=True,
        update=lambda s, c: sync_visibility(s, "_high", s.show_high),
    )
    show_stats: BoolProperty(
        name="Show Stats",
        default=False,
        description="Expand to show triangle counts per LOD",
    )


