def _tri_count(collection):
    """Return total triangle count across all mesh objects in a collection,
    including geometry generated by modifiers (uses the evaluated depsgraph)."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    total = 0
    for obj in collection.objects:
        if obj.type != "MESH" or not obj.data:
            continue
        obj_eval = obj.evaluated_get(depsgraph)
        mesh_eval = obj_eval.to_mesh()
        if mesh_eval is None:
            continue
        for poly in mesh_eval.polygons:
            total += poly.loop_total - 2
        obj_eval.to_mesh_clear()
    return total


def get_lod_suffixes(is_library=False):
    if is_library:
        return ["_morphs_low_lod0", "_morphs_low_lod1", "_morphs_low_lod2"]
    return ["_lod0", "_lod1", "_lod2", "_high"]


def sync_visibility(item, suffix_type, value):
    real_suffix = suffix_type
    if item.is_library:
        mapping = {
            "_lod0": "_morphs_low_lod0",
            "_lod1": "_morphs_low_lod1",
            "_lod2": "_morphs_low_lod2",
        }
        real_suffix = mapping.get(suffix_type, suffix_type)
    coll = bpy.data.collections.get(item.name + real_suffix)
    if coll:
        coll.hide_viewport = not value
        coll.hide_render = not value


def collapse_all_collections():
    for window in bpy.context.window_manager.windows:
        for area in window.screen.areas:
            if area.type == "OUTLINER":
                for region in area.regions:
                    if region.type == "WINDOW":
                        with bpy.context.temp_override(
                            window=window, area=area, region=region
                        ):
                            try:
                                bpy.ops.outliner.show_hierarchy(backfill=False)
                            except Exception:
                                pass
                        return


def detect_asset_from_name(name):
    lib_sfx = ["_morphs_low_lod0", "_morphs_low_lod1", "_morphs_low_lod2"]
    std_sfx = ["_lod0", "_lod1", "_lod2", "_high"]
    for s in lib_sfx:
        if s in name:
            return name.split(s)[0], True
    for s in std_sfx:
        if s in name:
            return name.split(s)[0], False
    return None, False


def perform_material_sync(base_name, use_two_mats):
    suffixes = ["_lod0", "_lod1", "_lod2", "_high"]
    for sfx in suffixes:
        coll = bpy.data.collections.get(base_name + sfx)
        if not coll:
            continue
        for obj in coll.objects:
            if obj.type != "MESH":
                continue
            if len(obj.material_slots) > 0 and obj.material_slots[0].material:
                obj.material_slots[0].material.name = f"A_{base_name}"
            if (
                use_two_mats
                and len(obj.material_slots) > 1
                and obj.material_slots[1].material
            ):
                obj.material_slots[1].material.name = f"Z_{base_name}"


def apply_modifiers_with_shapekeys(context, obj, target_collection):
    if not obj.data.shape_keys:
        bpy.ops.object.select_all(action="DESELECT")
        obj.select_set(True)
        context.view_layer.objects.active = obj
        bpy.ops.object.convert(target="MESH")
        return context.view_layer.objects.active

    original_name = obj.name
    original_solo = obj.show_only_shape_key
    original_active_index = obj.active_shape_key_index

    obj.show_only_shape_key = False

    armature_mods = [m for m in obj.modifiers if m.type == "ARMATURE"]
    for m in armature_mods:
        m.show_viewport = False

    depsgraph = context.evaluated_depsgraph_get()
    shape_keys = obj.data.shape_keys.key_blocks
    temp_meshes = []

    for sk in shape_keys:
        sk.value = 0.0

    for i in range(len(shape_keys)):
        sk = shape_keys[i]
        sk.value = 1.0
        obj.active_shape_key_index = i
        context.view_layer.update()

        obj_eval = obj.evaluated_get(depsgraph)
        mesh_eval = bpy.data.meshes.new_from_object(
            obj_eval, preserve_all_data_layers=True, depsgraph=depsgraph
        )
        temp_meshes.append(mesh_eval)
        sk.value = 0.0

    new_mesh_data = temp_meshes[0]
    new_obj = bpy.data.objects.new(original_name + "_applied", new_mesh_data)
    target_collection.objects.link(new_obj)

    # bpy.data.objects.new() defaults to identity transform; the original
    # obj's location/rotation/scale are NOT carried over. Without copying
    # them across, shape-keyed meshes processed by this helper land at
    # the world origin while their non-shape-keyed siblings (handled by
    # the bpy.ops.object.convert path above) keep their transforms — which
    # then produces inconsistent geometry positions after the caller's
    # transform_apply + join + export pipeline.
    new_obj.matrix_world = obj.matrix_world.copy()

    new_obj.shape_key_add(name=shape_keys[0].name)
    for i in range(1, len(temp_meshes)):
        new_sk = new_obj.shape_key_add(name=shape_keys[i].name)
        coords = [0.0] * len(temp_meshes[i].vertices) * 3
        temp_meshes[i].vertices.foreach_get("co", coords)
        new_sk.data.foreach_set("co", coords)
        bpy.data.meshes.remove(temp_meshes[i])

    bpy.data.objects.remove(obj, do_unlink=True)
    new_obj.name = original_name
    new_obj.show_only_shape_key = original_solo
    new_obj.active_shape_key_index = original_active_index

    # NOTE: We deliberately DO NOT re-add the Armature modifier here, even
    # though we removed it earlier (via show_viewport=False during shape
    # key evaluation, then implicit drop via the new_obj rebuild).
    #
    # The non-shape-keyed branch above uses bpy.ops.object.convert which
    # APPLIES every modifier including Armature into the mesh data, so it
    # also returns a modifier-free object. By mirroring that behaviour
    # here we keep the two branches symmetric — both return an unbound
    # mesh — which matters for downstream callers like Quick Export and
    # All-Class. They both immediately strip-then-re-add the Armature
    # modifier with the correct armature, and they BOTH need the mesh to
    # be unbound when transform_apply runs. With the old re-add behaviour,
    # the shape-keyed branch left an Armature mod attached, and a later
    # transform_apply on a still-bound mesh corrupted the bind matrix the
    # FBX exporter writes — non-shape-keyed exports came out correct
    # while shape-keyed exports retained the source variant's spread
    # offset on the armature in the engine.

    return new_obj



def _setup_asset_material_nodes(mat, asset_name):
    """
    Ensure *mat* has a clean Principled BSDF → Output graph and nothing else.
    The normal map subgraph is deliberately NOT added here — it is built only
    after the first bake via _wire_normal_image_to_material(), so the mesh
    shades normally in the viewport until a real bake exists.
    """
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    nodes.clear()

    bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.location = (0, 0)

    out = nodes.new("ShaderNodeOutputMaterial")
    out.location = (300, 0)
    links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])


def _collect_asset_materials(asset_name):
    """
    Return the list of unique materials actually used by the meshes in
    *asset_name*_lod0, in the order they're encountered. We use this
    instead of guessing 'A_<asset>' / 'Z_<asset>' because the All-Class
    flow renames asset/collection names but deliberately leaves the
    material names alone — every per-class variant shares the same
    materials as the original asset, regardless of what the asset is
    now called.
    """
    coll = bpy.data.collections.get(asset_name + "_lod0")
    if not coll:
        return []
    seen = []
    for obj in coll.objects:
        if obj.type != "MESH":
            continue
        for slot in obj.material_slots:
            if slot.material and slot.material not in seen:
                seen.append(slot.material)
    return seen


def _wire_normal_image_to_material(mat, image):
    """
    Called after a successful bake.  On the first call the full normal map
    subgraph is built and wired into the existing Principled BSDF:

      [Image Texture] → [Normal Map (DirectX, Tangent)] → [Principled BSDF]

    On subsequent calls (re-bakes) the existing Image Texture node is simply
    updated to point at the new image — nothing else changes.
    """
    if not mat or not mat.use_nodes:
        return

    nodes = mat.node_tree.nodes
    links = mat.node_tree.links

    # Check if the subgraph already exists
    img_node = next(
        (n for n in nodes if n.type == "TEX_IMAGE" and n.label == "_asset_normal_tex"),
        None,
    )
    if img_node:
        # Already wired — just swap the image
        img_node.image = image
        return

    # First bake: find the Principled BSDF to anchor position and link
    bsdf = next((n for n in nodes if n.type == "BSDF_PRINCIPLED"), None)
    base_x = bsdf.location.x if bsdf else 0
    base_y = bsdf.location.y if bsdf else 0

    # Normal Map node
    nm = nodes.new("ShaderNodeNormalMap")
    nm.location  = (base_x - 250, base_y - 200)
    nm.label     = "_asset_normal_map"
    nm.space = "TANGENT"

    if hasattr(nm, "convention"):
        # Blender 5.1+: native DirectX mode on the Normal Map node
        nm.convention = "DIRECTX"
        flip_node = None
    else:
        # Blender 5.0 and earlier: invert green via an RGB Curves node
        # placed between the Image Texture and the Normal Map node
        flip_node = nodes.new("ShaderNodeRGBCurve")
        flip_node.location = (base_x - 420, base_y - 200)
        flip_node.label    = "_asset_normal_flip_g"

        # curves[0]=C  curves[1]=G  curves[2]=R  curves[3]=B
        g_curve = flip_node.mapping.curves[1]
        # Default points are (0,0) and (1,1) — move them to invert the channel
        g_curve.points[0].location = (0.0, 1.0)
        g_curve.points[1].location = (1.0, 0.0)
        flip_node.mapping.update()

    # Image Texture node
    img_node = nodes.new("ShaderNodeTexImage")
    img_node.location      = (base_x - 700, base_y - 200)
    img_node.label         = "_asset_normal_tex"
    img_node.interpolation = "Linear"
    img_node.image         = image

    # Wire up
    if flip_node:
        links.new(img_node.outputs["Color"], flip_node.inputs["Color"])
        links.new(flip_node.outputs["Color"], nm.inputs["Color"])
    else:
        links.new(img_node.outputs["Color"], nm.inputs["Color"])
    if bsdf:
        links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])


